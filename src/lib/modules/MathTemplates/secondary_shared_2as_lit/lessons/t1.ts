function svgEconomicIndexChart(): string {
	const years = ['2021', '2022', '2023', '2024'];
	const indices = [100, 125, 150, 90];
	const w = 410;
	const h = 215;
	const ox = 52;
	const oy = 170;
	const plotH = 115;
	const maxIdx = 160;
	const parts: string[] = [
		`<rect x="8" y="8" width="${w - 16}" height="${h - 16}" rx="8" fill="#f8fafc" stroke="#cbd5e1" stroke-width="1.2"/>`,
		`<text x="${w / 2}" y="27" text-anchor="middle" font-size="12.5" font-weight="bold" fill="#0f172a">تطور الرقم القياسي لمبيعات دار نشر (الأساس 100 سنة 2021)</text>`,
		`<line x1="${ox}" y1="${oy - plotH - 8}" x2="${ox}" y2="${oy}" stroke="#0f172a" stroke-width="1.6"/>`,
		`<line x1="${ox}" y1="${oy}" x2="${w - 28}" y2="${oy}" stroke="#0f172a" stroke-width="1.6"/>`
	];
	// Base 100 dashed reference line
	const y100 = oy - (100 / maxIdx) * plotH;
	parts.push(
		`<line x1="${ox}" y1="${y100.toFixed(1)}" x2="${w - 28}" y2="${y100.toFixed(1)}" stroke="#dc2626" stroke-width="1.3" stroke-dasharray="5,4"/>`,
		`<text x="${ox - 6}" y="${(y100 + 4).toFixed(1)}" text-anchor="end" font-size="10" font-weight="bold" fill="#dc2626">100</text>`
	);
	const slot = 82;
	const barW = 38;
	years.forEach((yr, i) => {
		const idx = indices[i];
		const bh = (idx / maxIdx) * plotH;
		const bx = ox + 22 + i * slot;
		const by = oy - bh;
		const fill = idx >= 100 ? (idx === 100 ? '#64748b' : '#2563eb') : '#f59e0b';
		parts.push(
			`<rect x="${bx}" y="${by.toFixed(1)}" width="${barW}" height="${bh.toFixed(1)}" rx="3" fill="${fill}"/>`,
			`<text x="${bx + barW / 2}" y="${(by - 5).toFixed(1)}" text-anchor="middle" font-size="11" font-weight="bold" fill="#0f172a">${idx}</text>`,
			`<text x="${bx + barW / 2}" y="${oy + 16}" text-anchor="middle" font-size="11" font-weight="bold" fill="#334155">${yr}</text>`
		);
	});
	parts.push(
		`<text x="${w / 2}" y="${h - 14}" text-anchor="middle" font-size="10.5" font-weight="bold" fill="#1e3a8a">I_n = (X_n / X_0) × 100  |  نسبة التطور من سنة الأساس: e% = I_n - 100</text>`
	);
	return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${w} ${h}" width="${w}" height="${h}" font-family="Arabic Transparent" style="background:#ffffff;font-family:'Arabic Transparent',Arial,sans-serif">${parts.join('')}</svg>`;
}

