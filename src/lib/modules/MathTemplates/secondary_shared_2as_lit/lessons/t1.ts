function svgComparativeBoxPlot(): string {
	const w = 430;
	const h = 210;
	const xMin = 0;
	const xMax = 20;
	const x0 = 40;
	const x1 = 395;
	const toX = (v: number) => x0 + ((v - xMin) / (xMax - xMin)) * (x1 - x0);
	const parts: string[] = [
		`<rect x="8" y="8" width="${w - 16}" height="${h - 16}" rx="8" fill="#f8fafc" stroke="#cbd5e1" stroke-width="1.2"/>`,
		`<text x="${w / 2}" y="27" text-anchor="middle" font-size="12.5" font-weight="bold" fill="#0f172a">المخطط بالعلبة والمقارنة بين سلسلتين (القسم أ مقابل القسم ب)</text>`,
		`<line x1="${x0}" y1="168" x2="${x1}" y2="168" stroke="#0f172a" stroke-width="1.6"/>`
	];
	for (let t = 0; t <= 20; t += 2) {
		const px = toX(t);
		parts.push(
			`<line x1="${px.toFixed(1)}" y1="163" x2="${px.toFixed(1)}" y2="173" stroke="#334155" stroke-width="1.2"/>`,
			`<text x="${px.toFixed(1)}" y="186" text-anchor="middle" font-size="10" fill="#334155">${t}</text>`
		);
	}
	// Group A: min=2, Q1=5, Me=9, Q3=12, max=18 (y=68)
	const drawBox = (y: number, minV: number, q1: number, me: number, q3: number, maxV: number, col: string, fill: string, label: string) => {
		const pMin = toX(minV);
		const pQ1 = toX(q1);
		const pMe = toX(me);
		const pQ3 = toX(q3);
		const pMax = toX(maxV);
		parts.push(
			`<text x="${x0 - 4}" y="${y + 4}" text-anchor="end" font-size="11" font-weight="bold" fill="${col}">${label}</text>`,
			`<line x1="${pMin.toFixed(1)}" y1="${y}" x2="${pQ1.toFixed(1)}" y2="${y}" stroke="${col}" stroke-width="2"/>`,
			`<line x1="${pQ3.toFixed(1)}" y1="${y}" x2="${pMax.toFixed(1)}" y2="${y}" stroke="${col}" stroke-width="2"/>`,
			`<line x1="${pMin.toFixed(1)}" y1="${y - 9}" x2="${pMin.toFixed(1)}" y2="${y + 9}" stroke="${col}" stroke-width="2"/>`,
			`<line x1="${pMax.toFixed(1)}" y1="${y - 9}" x2="${pMax.toFixed(1)}" y2="${y + 9}" stroke="${col}" stroke-width="2"/>`,
			`<rect x="${pQ1.toFixed(1)}" y="${y - 14}" width="${(pQ3 - pQ1).toFixed(1)}" height="28" fill="${fill}" stroke="${col}" stroke-width="2"/>`,
			`<line x1="${pMe.toFixed(1)}" y1="${y - 14}" x2="${pMe.toFixed(1)}" y2="${y + 14}" stroke="#dc2626" stroke-width="2.4"/>`,
			`<text x="${pMin.toFixed(1)}" y="${y - 14}" text-anchor="middle" font-size="9.5" fill="#475569">${minV}</text>`,
			`<text x="${pQ1.toFixed(1)}" y="${y - 18}" text-anchor="middle" font-size="9.5" font-weight="bold" fill="${col}">Q1=${q1}</text>`,
			`<text x="${pMe.toFixed(1)}" y="${y + 25}" text-anchor="middle" font-size="9.5" font-weight="bold" fill="#dc2626">Me=${me}</text>`,
			`<text x="${pQ3.toFixed(1)}" y="${y - 18}" text-anchor="middle" font-size="9.5" font-weight="bold" fill="${col}">Q3=${q3}</text>`,
			`<text x="${pMax.toFixed(1)}" y="${y - 14}" text-anchor="middle" font-size="9.5" fill="#475569">${maxV}</text>`
		);
	};
	drawBox(64, 2, 5, 9, 12, 18, '#1d4ed8', '#dbeafe', 'أ');
	drawBox(122, 6, 9, 11, 13, 17, '#15803d', '#dcfce7', 'ب');
	return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${w} ${h}" width="${w}" height="${h}" font-family="Arabic Transparent" style="background:#ffffff;font-family:'Arabic Transparent',Arial,sans-serif">${parts.join('')}</svg>`;
}

