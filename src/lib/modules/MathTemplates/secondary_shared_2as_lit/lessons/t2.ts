function svgArithmeticStepsPlot(): string {
	const terms = [12, 16, 20, 24, 28];
	const w = 410;
	const h = 210;
	const ox = 52;
	const oy = 165;
	const plotH = 110;
	const maxV = 32;
	const slot = 68;
	const parts: string[] = [
		`<rect x="8" y="8" width="${w - 16}" height="${h - 16}" rx="8" fill="#f8fafc" stroke="#cbd5e1" stroke-width="1.2"/>`,
		`<text x="${w / 2}" y="27" text-anchor="middle" font-size="12.5" font-weight="bold" fill="#0f172a">التمثيل البياني لمتتالية حسابية u_n = 12 + 4n (خطوة ثابتة +4)</text>`,
		`<line x1="${ox}" y1="${oy - plotH}" x2="${ox}" y2="${oy}" stroke="#0f172a" stroke-width="1.5"/>`,
		`<line x1="${ox}" y1="${oy}" x2="${w - 28}" y2="${oy}" stroke="#0f172a" stroke-width="1.5"/>`
	];
	terms.forEach((v, n) => {
		const px = ox + 28 + n * slot;
		const py = oy - (v / maxV) * plotH;
		parts.push(
			`<line x1="${px}" y1="${oy}" x2="${px}" y2="${py.toFixed(1)}" stroke="#93c5fd" stroke-width="2" stroke-dasharray="3,2"/>`,
			`<circle cx="${px}" cy="${py.toFixed(1)}" r="5" fill="#1d4ed8"/>`,
			`<text x="${px}" y="${(py - 9).toFixed(1)}" text-anchor="middle" font-size="10.5" font-weight="bold" fill="#1e3a8a">u${n}=${v}</text>`,
			`<text x="${px}" y="${oy + 15}" text-anchor="middle" font-size="10.5" font-weight="bold" fill="#334155">n=${n}</text>`
		);
		if (n < terms.length - 1) {
			const nx = ox + 28 + (n + 1) * slot;
			const ny = oy - (terms[n + 1] / maxV) * plotH;
			parts.push(
				`<line x1="${px}" y1="${py.toFixed(1)}" x2="${nx}" y2="${ny.toFixed(1)}" stroke="#dc2626" stroke-width="1.4" stroke-dasharray="4,3"/>`,
				`<text x="${(px + nx) / 2}" y="${((py + ny) / 2 + 13).toFixed(1)}" text-anchor="middle" font-size="9.5" font-weight="bold" fill="#dc2626">+4</text>`
			);
		}
	});
	parts.push(
		`<text x="${w / 2}" y="${h - 12}" text-anchor="middle" font-size="10.5" font-weight="bold" fill="#334155">النقط (n ; u_n) تقع على استقامة واحدة لأن النمو خطي: u_{n+1} - u_n = r</text>`
	);
	return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${w} ${h}" width="${w}" height="${h}" font-family="Arabic Transparent" style="background:#ffffff;font-family:'Arabic Transparent',Arial,sans-serif">${parts.join('')}</svg>`;
}

