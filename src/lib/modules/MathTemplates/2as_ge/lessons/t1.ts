function escXml(str: string): string {
	return str
		.replaceAll('&', '&amp;')
		.replaceAll('<', '&lt;')
		.replaceAll('>', '&gt;')
		.replaceAll('"', '&quot;');
}

function svgBoxPlot(opts: {
	min: number;
	q1: number;
	median: number;
	q3: number;
	max: number;
	axisMin?: number;
	axisMax?: number;
	step?: number;
	title?: string;
}): string {
	const w = 400;
	const h = 155;
	const padL = 32;
	const padR = 28;
	const aMin = opts.axisMin ?? Math.floor(opts.min - 2);
	const aMax = opts.axisMax ?? Math.ceil(opts.max + 2);
	const step = opts.step ?? 2;
	const span = Math.max(1, aMax - aMin);
	const toX = (v: number) => padL + ((v - aMin) / span) * (w - padL - padR);

	const yBoxTop = 52;
	const yBoxBot = 92;
	const yMid = (yBoxTop + yBoxBot) / 2;
	const yAxis = 122;

	const xMin = toX(opts.min);
	const xQ1 = toX(opts.q1);
	const xMed = toX(opts.median);
	const xQ3 = toX(opts.q3);
	const xMax = toX(opts.max);

	const parts: string[] = [];
	parts.push(`<rect x="4" y="4" width="${w - 8}" height="${h - 8}" rx="8" fill="#ffffff" stroke="#cbd5e1" stroke-width="1.2"/>`);
	if (opts.title) {
		parts.push(`<text x="${w / 2}" y="22" text-anchor="middle" font-size="11.5" font-weight="bold" fill="#0f172a">${escXml(opts.title)}</text>`);
	}

	// Horizontal axis
	parts.push(`<line x1="${padL - 8}" y1="${yAxis}" x2="${w - padR + 10}" y2="${yAxis}" stroke="#334155" stroke-width="1.6"/>`);
	for (let v = aMin; v <= aMax; v += step) {
		const px = toX(v);
		parts.push(`<line x1="${px.toFixed(1)}" y1="${yAxis - 4}" x2="${px.toFixed(1)}" y2="${yAxis + 4}" stroke="#334155" stroke-width="1.4"/>`);
		parts.push(`<text x="${px.toFixed(1)}" y="${yAxis + 17}" text-anchor="middle" font-size="10" fill="#475569">${v}</text>`);
	}

	// Whiskers
	parts.push(`<line x1="${xMin.toFixed(1)}" y1="${yMid}" x2="${xQ1.toFixed(1)}" y2="${yMid}" stroke="#1e293b" stroke-width="2"/>`);
	parts.push(`<line x1="${xQ3.toFixed(1)}" y1="${yMid}" x2="${xMax.toFixed(1)}" y2="${yMid}" stroke="#1e293b" stroke-width="2"/>`);
	parts.push(`<line x1="${xMin.toFixed(1)}" y1="${yMid - 10}" x2="${xMin.toFixed(1)}" y2="${yMid + 10}" stroke="#1e293b" stroke-width="2"/>`);
	parts.push(`<line x1="${xMax.toFixed(1)}" y1="${yMid - 10}" x2="${xMax.toFixed(1)}" y2="${yMid + 10}" stroke="#1e293b" stroke-width="2"/>`);

	// Box Q1..Q3
	parts.push(`<rect x="${xQ1.toFixed(1)}" y="${yBoxTop}" width="${Math.max(4, xQ3 - xQ1).toFixed(1)}" height="${yBoxBot - yBoxTop}" fill="rgba(37,99,235,0.16)" stroke="#1d4ed8" stroke-width="2"/>`);

	// Median line
	parts.push(`<line x1="${xMed.toFixed(1)}" y1="${yBoxTop}" x2="${xMed.toFixed(1)}" y2="${yBoxBot}" stroke="#dc2626" stroke-width="2.6"/>`);

	// Labels above
	parts.push(`<text x="${xMin.toFixed(1)}" y="${yMid - 14}" text-anchor="middle" font-size="10" font-weight="bold" fill="#334155">Min=${opts.min}</text>`);
	parts.push(`<text x="${xQ1.toFixed(1)}" y="${yBoxTop - 7}" text-anchor="middle" font-size="10" font-weight="bold" fill="#1d4ed8">Q1=${opts.q1}</text>`);
	parts.push(`<text x="${xMed.toFixed(1)}" y="${yBoxTop - 7}" text-anchor="middle" font-size="10.5" font-weight="bold" fill="#dc2626">Me=${opts.median}</text>`);
	parts.push(`<text x="${xQ3.toFixed(1)}" y="${yBoxTop - 7}" text-anchor="middle" font-size="10" font-weight="bold" fill="#1d4ed8">Q3=${opts.q3}</text>`);
	parts.push(`<text x="${xMax.toFixed(1)}" y="${yMid - 14}" text-anchor="middle" font-size="10" font-weight="bold" fill="#334155">Max=${opts.max}</text>`);

	return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${w} ${h}" width="${w}" height="${h}" style="background:#ffffff;font-family:Cairo,Arial,sans-serif">${parts.join('')}</svg>`;
}

