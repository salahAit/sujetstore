const SVG_FONT = 'Cairo,Arial,sans-serif';

function svgWrap(w: number, h: number, body: string): string {
	return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${w} ${h}" width="${w}" height="${h}" style="background:#ffffff;font-family:${SVG_FONT}">${body}</svg>`;
}

/** Cumulative frequency table SVG for Lesson 1. */
function svgCumulativeTable(): string {
	const w = 380;
	const h = 152;
	const col0 = 132;
	const cols = [1, 2, 3, 4, 5];
	const freqs = [4, 8, 12, 6, 10];
	const cumUp = [4, 12, 24, 30, 40];
	const cumDown = [40, 36, 28, 16, 10];
	const cw = (w - col0 - 12) / cols.length;
	const rowH = 32;
	const parts: string[] = [];

	parts.push(`<rect x="6" y="8" width="${w - 12}" height="${rowH * 4}" fill="#ffffff" stroke="#0f172a" stroke-width="1.3"/>`);
	for (let r = 1; r < 4; r++) {
		parts.push(`<line x1="6" y1="${8 + r * rowH}" x2="${w - 6}" y2="${8 + r * rowH}" stroke="#334155" stroke-width="1"/>`);
	}
	parts.push(`<line x1="${col0}" y1="8" x2="${col0}" y2="${8 + rowH * 4}" stroke="#0f172a" stroke-width="1.3"/>`);
	for (let c = 1; c < cols.length; c++) {
		const x = col0 + c * cw;
		parts.push(`<line x1="${x.toFixed(1)}" y1="8" x2="${x.toFixed(1)}" y2="${8 + rowH * 4}" stroke="#cbd5e1" stroke-width="1"/>`);
	}

	const labels = ['القيمة xᵢ (عدد الكتب)', 'التكرار nᵢ', 'ت. م. صاعد', 'ت. م. نازل'];
	const labelColors = ['#0f172a', '#1d4ed8', '#15803d', '#b91c1c'];
	const rowsData = [cols, freqs, cumUp, cumDown];

	labels.forEach((lbl, r) => {
		const cy = 8 + r * rowH + 21;
		parts.push(`<text x="${col0 / 2 + 3}" y="${cy}" text-anchor="middle" font-size="11" font-weight="bold" fill="${labelColors[r]}">${lbl}</text>`);
		rowsData[r].forEach((val, c) => {
			const cx = col0 + c * cw + cw / 2;
			parts.push(`<text x="${cx.toFixed(1)}" y="${cy}" text-anchor="middle" font-size="11.5" font-weight="bold" fill="${labelColors[r]}">${val}</text>`);
		});
	});
	return svgWrap(w, h, parts.join(''));
}

/** Pie chart SVG for 60 students choosing literary genres: 15 (90°), 20 (120°), 10 (60°), 15 (90°). */
function svgLiteraryPieChart(): string {
	const w = 380;
	const h = 210;
	const cx = 115;
	const cy = 108;
	const r = 74;
	const slices = [
		{ label: 'الشعر', count: 15, deg: 90, color: '#2563eb' },
		{ label: 'القصة', count: 20, deg: 120, color: '#16a34a' },
		{ label: 'المسرح', count: 10, deg: 60, color: '#f59e0b' },
		{ label: 'المقال', count: 15, deg: 90, color: '#dc2626' }
	];
	const parts: string[] = [];
	parts.push(`<text x="190" y="20" text-anchor="middle" font-size="12.5" font-weight="bold" fill="#0f172a">توزيع 60 تلميذاً حسب الفن الأدبي المفضل</text>`);

	let startDeg = -90;
	slices.forEach((s, idx) => {
		const endDeg = startDeg + s.deg;
		const a1 = (startDeg * Math.PI) / 180;
		const a2 = (endDeg * Math.PI) / 180;
		const x1 = cx + r * Math.cos(a1);
		const y1 = cy + r * Math.sin(a1);
		const x2 = cx + r * Math.cos(a2);
		const y2 = cy + r * Math.sin(a2);
		const largeArc = s.deg > 180 ? 1 : 0;
		parts.push(`<path d="M ${cx} ${cy} L ${x1.toFixed(1)} ${y1.toFixed(1)} A ${r} ${r} 0 ${largeArc} 1 ${x2.toFixed(1)} ${y2.toFixed(1)} Z" fill="${s.color}" stroke="#ffffff" stroke-width="2"/>`);

		const mid = ((startDeg + endDeg) / 2) * (Math.PI / 180);
		const tx = cx + r * 0.58 * Math.cos(mid);
		const ty = cy + r * 0.58 * Math.sin(mid) + 4;
		parts.push(`<text x="${tx.toFixed(1)}" y="${ty.toFixed(1)}" text-anchor="middle" font-size="10.5" font-weight="bold" fill="#ffffff">${s.deg}°</text>`);

		// Legend
		const ly = 56 + idx * 34;
		parts.push(`<rect x="224" y="${ly - 12}" width="14" height="14" rx="3" fill="${s.color}"/>`);
		parts.push(`<text x="246" y="${ly}" font-size="11.5" font-weight="bold" fill="#0f172a">${s.label}: ${s.count} (${s.deg}°)</text>`);
		startDeg = endDeg;
	});
	return svgWrap(w, h, parts.join(''));
}

/** Histogram SVG for continuous classes [0,2[, [2,4[, [4,6[, [6,8[. */
function svgHistogramClasses(): string {
	const w = 380;
	const h = 190;
	const ox = 48;
	const oy = 148;
	const cw = 68;
	const bars = [
		{ bounds: [0, 2], n: 5, col: '#93c5fd' },
		{ bounds: [2, 4], n: 12, col: '#60a5fa' },
		{ bounds: [4, 6], n: 9, col: '#3b82f6' },
		{ bounds: [6, 8], n: 4, col: '#2563eb' }
	];
	const maxN = 14;
	const plotH = 104;
	const parts: string[] = [];
	parts.push(`<text x="190" y="20" text-anchor="middle" font-size="12" font-weight="bold" fill="#0f172a">المدرج التكراري لسلسلة مجمعة في فئات متساوية الطول</text>`);
	parts.push(`<line x1="${ox}" y1="${oy - plotH - 8}" x2="${ox}" y2="${oy}" stroke="#0f172a" stroke-width="1.8"/>`);
	parts.push(`<line x1="${ox}" y1="${oy}" x2="${ox + cw * 4 + 20}" y2="${oy}" stroke="#0f172a" stroke-width="1.8"/>`);
	parts.push(`<text x="${ox - 8}" y="${oy - plotH - 10}" font-size="10.5" font-weight="bold" fill="#0f172a">nᵢ</text>`);

	bars.forEach((b, i) => {
		const bh = (b.n / maxN) * plotH;
		const bx = ox + i * cw;
		const by = oy - bh;
		parts.push(`<rect x="${bx}" y="${by.toFixed(1)}" width="${cw}" height="${bh.toFixed(1)}" fill="${b.col}" stroke="#1e3a8a" stroke-width="1.4"/>`);
		parts.push(`<text x="${bx + cw / 2}" y="${(by - 5).toFixed(1)}" text-anchor="middle" font-size="11" font-weight="bold" fill="#0f172a">${b.n}</text>`);
		parts.push(`<text x="${bx}" y="${oy + 16}" text-anchor="middle" font-size="10.5" fill="#334155">${b.bounds[0]}</text>`);
	});
	parts.push(`<text x="${ox + 4 * cw}" y="${oy + 16}" text-anchor="middle" font-size="10.5" fill="#334155">8</text>`);
	return svgWrap(w, h, parts.join(''));
}

