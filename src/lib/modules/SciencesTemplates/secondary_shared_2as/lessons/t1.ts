function svgPostprandialGlycemiaPlot(): string {
	return svgBioCurvePlot({
		xMin: 0,
		xMax: 5,
		yMin: 0,
		yMax: 2.2,
		xStep: 1,
		yStep: 0.4,
		xLabel: 't (h)',
		yLabel: 'G (g/L)',
		title: 'تطور تحلون الدم ونسبة الأنسولين بعد تناول وجبة غنية بالسكريات',
		eventArrows: [{ x: 0.5, label: 'وجبة سكرية', color: '#dc2626' }],
		dashedGuides: [
			{ x1: 0, y1: 1.0, x2: 5, y2: 1.0, color: '#15803d', label: 'القيمة المرجعية 1' }
		],
		curves: [
			{
				fn: (t) =>
					t < 0.5
						? 0.95
						: 0.95 + 0.72 * ((t - 0.5) / 1.0) * Math.exp(1 - (t - 0.5) / 1.0),
				color: '#dc2626',
				label: 'تحلون الدم'
			},
			{
				fn: (t) =>
					t < 0.7
						? 0.4
						: 0.4 + 1.15 * ((t - 0.7) / 1.1) * Math.exp(1 - (t - 0.7) / 1.1),
				color: '#2563eb',
				dashed: true,
				label: 'إفراز الأنسولين'
			}
		],
		points: [
			{ x: 1.5, y: 1.67, label: 'إفراط عابر', color: '#dc2626' },
			{ x: 4.5, y: 1.05, label: 'عودة للتوازن', color: '#15803d' }
		]
	});
}

function svgSynapticSummationPlot(): string {
	return svgBioCurvePlot({
		xMin: 0,
		xMax: 10,
		yMin: -85,
		yMax: 45,
		xStep: 2,
		yStep: 20,
		xLabel: 't (ms)',
		yLabel: 'Vm (mV)',
		title: 'التسجيل الغشائي للإدماج العصبي في العصبون المحرك',
		dashedGuides: [
			{ x1: 0, y1: -70, x2: 10, y2: -70, color: '#64748b', label: 'كمون الراحة' },
			{ x1: 0, y1: -55, x2: 10, y2: -55, color: '#dc2626', label: 'عتبة زوال الاستقطاب' }
		],
		curves: [
			{
				fn: (t) => {
					if (t < 2) return -70;
					if (t < 4) return -70 + 18 * Math.exp(-Math.pow((t - 3) / 0.55, 2));
					if (t < 6.2) return -70;
					if (t < 7.2) return -70 + 102 * Math.exp(-Math.pow((t - 6.7) / 0.25, 2));
					if (t < 8.5) return -70 - 8 * Math.exp(-Math.pow((t - 7.5) / 0.35, 2));
					return -70;
				},
				color: '#1d4ed8',
				label: 'محصلة تجميع منبه'
			},
			{
				fn: (t) => -70 - 10 * Math.exp(-Math.pow((t - 3) / 0.6, 2)),
				color: '#0f766e',
				dashed: true,
				label: 'مشبك مثبط'
			}
		],
		points: [
			{ x: 6.7, y: 32, label: 'كمون عمل', color: '#dc2626' },
			{ x: 3.0, y: -80, label: 'فرط استقطاب', color: '#0f766e' }
		]
	});
}

