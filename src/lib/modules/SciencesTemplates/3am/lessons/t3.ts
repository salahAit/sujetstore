function svgSoilProfileAndFormation(): string {
	let body = `<rect x="6" y="6" width="448" height="242" rx="10" fill="#f8fafc" stroke="#cbd5e1" stroke-width="1.3"/>`;
	body += `<text x="230" y="26" text-anchor="middle" font-size="13" font-weight="bold" fill="#0f172a">مراحل تشكل التربة انطلاقاً من الصخرة الأم وآفاقها</text>`;
	const stages = [
		{ x: 376, title: '1) الصخرة الأم', desc: 'صخرة متماسكة تتشقق', hO: 0, hA: 0, hB: 20 },
		{ x: 278, title: '2) تفكك أولي', desc: 'تجوية + كائنات رائدة', hO: 6, hA: 18, hB: 36 },
		{ x: 180, title: '3) تربة فتية', desc: 'تشكل الدبال والجذور', hO: 12, hA: 34, hB: 44 },
		{ x: 82, title: '4) تربة ناضجة', desc: 'آفاق واضحة وغطاء كثيف', hO: 16, hA: 48, hB: 48 }
	];
	for (const st of stages) {
		body += `<rect x="${st.x - 42}" y="44" width="84" height="178" rx="8" fill="#ffffff" stroke="#78350f" stroke-width="1.5"/>`;
		body += `<text x="${st.x}" y="62" text-anchor="middle" font-size="10.2" font-weight="bold" fill="#78350f">${esc(st.title)}</text>`;
		const baseY = 194;
		// Bedrock
		body += `<rect x="${st.x - 36}" y="${baseY - 26}" width="72" height="26" fill="#64748b"/>`;
		// Horizon B (fragments)
		body += `<rect x="${st.x - 36}" y="${baseY - 26 - st.hB}" width="72" height="${st.hB}" fill="#d97706" opacity="0.5"/>`;
		// Horizon A (humus + mineral)
		if (st.hA > 0) {
			body += `<rect x="${st.x - 36}" y="${baseY - 26 - st.hB - st.hA}" width="72" height="${st.hA}" fill="#78350f" opacity="0.82"/>`;
		}
		// Horizon O (litter + green shoots)
		if (st.hO > 0) {
			const topY = baseY - 26 - st.hB - st.hA - st.hO;
			body += `<rect x="${st.x - 36}" y="${topY}" width="72" height="${st.hO}" fill="#15803d" opacity="0.85"/>`;
		}
		body += `<text x="${st.x}" y="212" text-anchor="middle" font-size="9" fill="#334155">${esc(st.desc)}</text>`;
	}
	return wrapSciencesSvg(460, 254, body);
}

