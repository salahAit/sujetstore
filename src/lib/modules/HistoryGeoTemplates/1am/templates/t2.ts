function makeOrdering(
	ordered: string[],
	rng: SeededRng
): { items: string[]; correctOrder: number[] } {
	let items = rng.shuffle(ordered);
	if (JSON.stringify(items) === JSON.stringify(ordered) && ordered.length > 1) {
		items = [...ordered.slice(1), ordered[0]];
	}
	return {
		items,
		correctOrder: ordered.map((item) => items.indexOf(item))
	};
}

function makeCloze(
	sentence: string,
	correctOption: string,
	distractors: string[],
	rng: SeededRng
): { sentence: string; options: string[]; correctIndex: number } {
	const options = rng.shuffle([correctOption, ...distractors]);
	return {
		sentence,
		options,
		correctIndex: options.indexOf(correctOption)
	};
}

