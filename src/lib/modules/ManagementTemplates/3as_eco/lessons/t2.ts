const FONT_AR = "'Cairo', 'Noto Naskh Arabic', 'Arabic Transparent', sans-serif";

function escXml(s: string): string {
	return s
		.replace(/&/g, '&amp;')
		.replace(/</g, '&lt;')
		.replace(/>/g, '&gt;')
		.replace(/"/g, '&quot;');
}

function svgCardsDiagram(
	title: string,
	cards: Array<{ badge: string; heading: string; sub: string; color: string }>
): string {
	const W = 640;
	const cols = 2;
	const cardW = 286;
	const cardH = 74;
	const gapY = 14;
	const rows = Math.ceil(cards.length / cols);
	const H = 56 + rows * (cardH + gapY) + 12;

	const boxes = cards
		.map((c, idx) => {
			const row = Math.floor(idx / cols);
			const col = idx % cols;
			const x = col === 0 ? W - 24 - cardW : 24;
			const y = 48 + row * (cardH + gapY);
			return `<g>
  <rect x="${x}" y="${y}" width="${cardW}" height="${cardH}" rx="10" fill="#ffffff" stroke="${c.color}" stroke-width="1.6"/>
  <rect x="${x + cardW - 34}" y="${y + 12}" width="24" height="24" rx="12" fill="${c.color}"/>
  <text x="${x + cardW - 22}" y="${y + 28}" text-anchor="middle" font-family="${FONT_AR}" font-size="12" font-weight="700" fill="#ffffff">${escXml(c.badge)}</text>
  <text x="${x + cardW - 44}" y="${y + 28}" text-anchor="end" direction="rtl" font-family="${FONT_AR}" font-size="13" font-weight="700" fill="${c.color}">${escXml(c.heading)}</text>
  <text x="${x + cardW - 14}" y="${y + 54}" text-anchor="end" direction="rtl" font-family="${FONT_AR}" font-size="11" fill="#334155">${escXml(c.sub)}</text>
</g>`;
		})
		.join('\n');

	return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${W} ${H}" width="${W}" height="${H}" role="img" aria-label="${escXml(title)}">
  <rect width="${W}" height="${H}" rx="14" fill="#f8fafc" stroke="#cbd5e1" stroke-width="1.4"/>
  <text x="${W / 2}" y="28" text-anchor="middle" direction="rtl" font-family="${FONT_AR}" font-size="14.5" font-weight="700" fill="#0f172a">${escXml(title)}</text>
  ${boxes}
</svg>`;
}

function svgMaslowPyramid(title: string): string {
	const W = 640;
	const H = 225;
	const levels = [
		{ label: '5. تحقيق الذات والإبداع', w: 190, color: '#7c3aed' },
		{ label: '4. التقدير والاحترام والمكانة', w: 260, color: '#1d4ed8' },
		{ label: '3. الانتماء والعلاقات الاجتماعية', w: 330, color: '#0f766e' },
		{ label: '2. الأمان والاستقرار الوظيفي', w: 400, color: '#047857' },
		{ label: '1. الحاجات الفيزيولوجية الأساسية (الأجر العادل)', w: 480, color: '#b45309' }
	];
	const bars = levels
		.map((lv, i) => {
			const y = 44 + i * 33;
			const x = (W - lv.w) / 2;
			return `<rect x="${x}" y="${y}" width="${lv.w}" height="28" rx="7" fill="${lv.color}"/>
<text x="${W / 2}" y="${y + 19}" text-anchor="middle" direction="rtl" font-family="${FONT_AR}" font-size="11.5" font-weight="700" fill="#ffffff">${escXml(lv.label)}</text>`;
		})
		.join('\n');

	return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${W} ${H}" width="${W}" height="${H}" role="img" aria-label="${escXml(title)}">
  <rect width="${W}" height="${H}" rx="14" fill="#f8fafc" stroke="#cbd5e1" stroke-width="1.4"/>
  <text x="${W / 2}" y="26" text-anchor="middle" direction="rtl" font-family="${FONT_AR}" font-size="14" font-weight="700" fill="#0f172a">${escXml(title)}</text>
  ${bars}
</svg>`;
}

