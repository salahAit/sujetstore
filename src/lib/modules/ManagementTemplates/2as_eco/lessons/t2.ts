const FONT_AR = "'Cairo', 'Noto Naskh Arabic', 'Arabic Transparent', sans-serif";

function escXml(s: string): string {
	return s
		.replace(/&/g, '&amp;')
		.replace(/</g, '&lt;')
		.replace(/>/g, '&gt;')
		.replace(/"/g, '&quot;');
}

function svgCardsDiagram(
	title: string,
	cards: Array<{ badge: string; heading: string; sub: string; color: string }>
): string {
	const W = 640;
	const cols = 2;
	const cardW = 286;
	const cardH = 74;
	const gapY = 14;
	const rows = Math.ceil(cards.length / cols);
	const H = 56 + rows * (cardH + gapY) + 12;

	const boxes = cards
		.map((c, idx) => {
			const row = Math.floor(idx / cols);
			const col = idx % cols;
			const x = col === 0 ? W - 24 - cardW : 24;
			const y = 48 + row * (cardH + gapY);
			return `<g>
  <rect x="${x}" y="${y}" width="${cardW}" height="${cardH}" rx="10" fill="#ffffff" stroke="${c.color}" stroke-width="1.6"/>
  <rect x="${x + cardW - 34}" y="${y + 12}" width="24" height="24" rx="12" fill="${c.color}"/>
  <text x="${x + cardW - 22}" y="${y + 28}" text-anchor="middle" font-family="${FONT_AR}" font-size="12" font-weight="700" fill="#ffffff">${escXml(c.badge)}</text>
  <text x="${x + cardW - 44}" y="${y + 28}" text-anchor="end" direction="rtl" font-family="${FONT_AR}" font-size="13" font-weight="700" fill="${c.color}">${escXml(c.heading)}</text>
  <text x="${x + cardW - 14}" y="${y + 54}" text-anchor="end" direction="rtl" font-family="${FONT_AR}" font-size="11" fill="#334155">${escXml(c.sub)}</text>
</g>`;
		})
		.join('\n');

	return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${W} ${H}" width="${W}" height="${H}" role="img" aria-label="${escXml(title)}">
  <rect width="${W}" height="${H}" rx="14" fill="#f8fafc" stroke="#cbd5e1" stroke-width="1.4"/>
  <text x="${W / 2}" y="28" text-anchor="middle" direction="rtl" font-family="${FONT_AR}" font-size="14.5" font-weight="700" fill="#0f172a">${escXml(title)}</text>
  ${boxes}
</svg>`;
}

function svgOrgHierarchy(title: string, gm: string, units: Array<{ name: string; color: string }>): string {
	const W = 640;
	const H = 200;
	const n = units.length;
	const boxW = Math.floor((W - 48 - (n - 1) * 16) / n);
	const children = units
		.map((u, i) => {
			const x = W - 24 - (i + 1) * boxW - i * 16;
			const cx = x + boxW / 2;
			return `<line x1="${cx}" y1="104" x2="${cx}" y2="122" stroke="${u.color}" stroke-width="2"/>
<rect x="${x}" y="122" width="${boxW}" height="52" rx="9" fill="#ffffff" stroke="${u.color}" stroke-width="1.8"/>
<text x="${cx}" y="152" text-anchor="middle" direction="rtl" font-family="${FONT_AR}" font-size="12" font-weight="700" fill="${u.color}">${escXml(u.name)}</text>`;
		})
		.join('\n');
	const firstCx = W - 24 - boxW / 2;
	const lastCx = 24 + boxW / 2;

	return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${W} ${H}" width="${W}" height="${H}" role="img" aria-label="${escXml(title)}">
  <rect width="${W}" height="${H}" rx="14" fill="#f8fafc" stroke="#cbd5e1" stroke-width="1.4"/>
  <text x="${W / 2}" y="24" text-anchor="middle" direction="rtl" font-family="${FONT_AR}" font-size="14" font-weight="700" fill="#0f172a">${escXml(title)}</text>
  <rect x="${W / 2 - 110}" y="42" width="220" height="40" rx="10" fill="#0f766e"/>
  <text x="${W / 2}" y="67" text-anchor="middle" direction="rtl" font-family="${FONT_AR}" font-size="13" font-weight="700" fill="#ffffff">${escXml(gm)}</text>
  <line x1="${W / 2}" y1="82" x2="${W / 2}" y2="104" stroke="#475569" stroke-width="2"/>
  <line x1="${lastCx}" y1="104" x2="${firstCx}" y2="104" stroke="#475569" stroke-width="2"/>
  ${children}
</svg>`;
}

