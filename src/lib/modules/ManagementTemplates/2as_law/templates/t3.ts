type QuizSpec =
	| {
			kind: 'mcq';
			q: string;
			correct: string;
			distractors: { text: string; diagnosticFeedback: string }[];
			explanation: string;
	  }
	| {
			kind: 'true_false';
			q: string;
			correctAnswer: boolean;
			explanation: string;
	  }
	| {
			kind: 'matching';
			q: string;
			pairs: Array<{ left: string; right: string }>;
			explanation: string;
	  }
	| {
			kind: 'ordering';
			q: string;
			orderedItems: string[];
			explanation: string;
	  }
	| {
			kind: 'drag_drop';
			q: string;
			categories: string[];
			items: Array<{ text: string; category: number }>;
			explanation: string;
	  }
	| {
			kind: 'cloze';
			q: string;
			sentence: string;
			correct: string;
			distractors: string[];
			explanation: string;
	  };

function buildInteractiveQuiz(
	spec: QuizSpec,
	rng: SeededRng
): { quizQuestion: QuizQuestionPayload; finalAnswer: string } {
	switch (spec.kind) {
		case 'mcq': {
			const mcq = buildUniqueMcqOptions(spec.correct, spec.distractors, rng);
			return {
				finalAnswer: spec.correct,
				quizQuestion: {
					type: 'mcq',
					questionText: spec.q,
					questionTextAr: spec.q,
					questionData: {
						options: mcq.options,
						correctIndices: mcq.correctIndices,
						correctIndexes: mcq.correctIndices
					},
					explanation: `${spec.explanation} الإجابة الصحيحة: ${spec.correct}.`
				}
			};
		}
		case 'true_false':
			return {
				finalAnswer: spec.correctAnswer ? 'صحيح' : 'خطأ',
				quizQuestion: {
					type: 'true_false',
					questionText: spec.q,
					questionTextAr: spec.q,
					questionData: { correctAnswer: spec.correctAnswer },
					explanation: spec.explanation
				}
			};
		case 'matching': {
			const pairs = rng.shuffle(spec.pairs);
			return {
				finalAnswer: pairs.map((p) => `${p.left} — ${p.right}`).join(' | '),
				quizQuestion: {
					type: 'matching',
					questionText: spec.q,
					questionTextAr: spec.q,
					questionData: { pairs },
					explanation: spec.explanation
				}
			};
		}
		case 'ordering': {
			const shuffled = rng.shuffle(spec.orderedItems);
			if (shuffled.length > 1 && shuffled.every((x, i) => x === spec.orderedItems[i])) {
				[shuffled[0], shuffled[1]] = [shuffled[1], shuffled[0]];
			}
			const correctOrder = spec.orderedItems.map((item) => shuffled.indexOf(item));
			return {
				finalAnswer: spec.orderedItems.join(' ثم '),
				quizQuestion: {
					type: 'ordering',
					questionText: spec.q,
					questionTextAr: spec.q,
					questionData: { items: shuffled, correctOrder },
					explanation: spec.explanation
				}
			};
		}
		case 'drag_drop': {
			const items = rng.shuffle(spec.items);
			return {
				finalAnswer: spec.items
					.map((it) => `${it.text} (${spec.categories[it.category]})`)
					.join(' | '),
				quizQuestion: {
					type: 'drag_drop',
					questionText: spec.q,
					questionTextAr: spec.q,
					questionData: { categories: spec.categories, items },
					explanation: spec.explanation
				}
			};
		}
		case 'cloze': {
			const distractors = spec.distractors.filter((d) => d !== spec.correct).slice(0, 3);
			const options = rng.shuffle([spec.correct, ...distractors]);
			const correctIndex = options.indexOf(spec.correct);
			return {
				finalAnswer: spec.correct,
				quizQuestion: {
					type: 'cloze',
					questionText: spec.q,
					questionTextAr: spec.q,
					questionData: { sentence: spec.sentence, options, correctIndex },
					explanation: `${spec.explanation} الإجابة الصحيحة: ${spec.correct}.`
				}
			};
		}
	}
}

