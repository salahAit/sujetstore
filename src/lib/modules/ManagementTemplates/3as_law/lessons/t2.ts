const SVG_FONT = "'Cairo', 'Noto Naskh Arabic', 'Arabic Transparent', sans-serif";

function escSvg(s: string): string {
	return s
		.replace(/&/g, '&amp;')
		.replace(/</g, '&lt;')
		.replace(/>/g, '&gt;')
		.replace(/"/g, '&quot;');
}

function svgLawCards(opts: {
	title: string;
	subtitle?: string;
	cards: Array<{ badge: string; title: string; line1: string; line2?: string; color: string }>;
}): string {
	const cols = 2;
	const rows = Math.ceil(opts.cards.length / cols);
	const W = 640;
	const headerH = opts.subtitle ? 64 : 46;
	const padX = 18;
	const gap = 12;
	const cardW = (W - padX * 2 - gap) / cols;
	const cardH = 92;
	const H = headerH + rows * cardH + (rows - 1) * gap + 18;

	const cardsSvg = opts.cards
		.map((c, idx) => {
			const r = Math.floor(idx / cols);
			const colIdx = cols - 1 - (idx % cols);
			const x = padX + colIdx * (cardW + gap);
			const y = headerH + r * (cardH + gap);
			return `<g>
  <rect x="${x}" y="${y}" width="${cardW}" height="${cardH}" rx="10" fill="#ffffff" stroke="${c.color}" stroke-width="1.6"/>
  <rect x="${x + cardW - 5}" y="${y}" width="5" height="${cardH}" rx="2" fill="${c.color}"/>
  <rect x="${x + cardW - 44}" y="${y + 10}" width="34" height="22" rx="6" fill="${c.color}"/>
  <text x="${x + cardW - 27}" y="${y + 25}" text-anchor="middle" font-family="${SVG_FONT}" font-size="11" font-weight="700" fill="#ffffff">${escSvg(c.badge)}</text>
  <text x="${x + cardW - 52}" y="${y + 26}" text-anchor="end" direction="rtl" font-family="${SVG_FONT}" font-size="13" font-weight="700" fill="#0f172a">${escSvg(c.title)}</text>
  <text x="${x + cardW - 14}" y="${y + 52}" text-anchor="end" direction="rtl" font-family="${SVG_FONT}" font-size="11.5" fill="#334155">${escSvg(c.line1)}</text>
  ${c.line2 ? `<text x="${x + cardW - 14}" y="${y + 72}" text-anchor="end" direction="rtl" font-family="${SVG_FONT}" font-size="11" fill="#475569">${escSvg(c.line2)}</text>` : ''}
</g>`;
		})
		.join('\n');

	return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${W} ${H}" width="${W}" height="${H}" role="img" aria-label="${escSvg(opts.title)}">
  <rect width="${W}" height="${H}" rx="14" fill="#f0fdfa" stroke="#99f6e4" stroke-width="1.4"/>
  <text x="${W / 2}" y="28" text-anchor="middle" direction="rtl" font-family="${SVG_FONT}" font-size="15.5" font-weight="700" fill="#0f766e">${escSvg(opts.title)}</text>
  ${opts.subtitle ? `<text x="${W / 2}" y="49" text-anchor="middle" direction="rtl" font-family="${SVG_FONT}" font-size="12" fill="#475569">${escSvg(opts.subtitle)}</text>` : ''}
  ${cardsSvg}
</svg>`;
}

