function buildMcqForDifficulty(
	v: {
		easyQ: string;
		easyCorrect: string;
		easyDistractors: { text: string; diagnosticFeedback: string }[];
		medQ: string;
		medCorrect: string;
		medDistractors: { text: string; diagnosticFeedback: string }[];
		hardQ: string;
		hardCorrect: string;
		hardDistractors: { text: string; diagnosticFeedback: string }[];
		explanation: string;
	},
	difficulty: Difficulty,
	rng: SeededRng
): { quizQuestion: QuizQuestionPayload; finalAnswer: string } {
	const cfg =
		difficulty === 'easy'
			? { q: v.easyQ, ans: v.easyCorrect, dist: v.easyDistractors }
			: difficulty === 'medium'
				? { q: v.medQ, ans: v.medCorrect, dist: v.medDistractors }
				: { q: v.hardQ, ans: v.hardCorrect, dist: v.hardDistractors };
	const mcq = buildUniqueMcqOptions(cfg.ans, cfg.dist, rng);
	return {
		finalAnswer: cfg.ans,
		quizQuestion: {
			type: 'mcq',
			questionText: cfg.q,
			questionTextAr: cfg.q,
			questionData: {
				options: mcq.options,
				correctIndices: mcq.correctIndices,
				correctIndexes: mcq.correctIndices
			},
			explanation: `${v.explanation} الإجابة الصحيحة: ${cfg.ans}.`
		}
	};
}

