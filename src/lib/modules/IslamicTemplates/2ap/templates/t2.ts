function makeRng(seed: number, difficulty: Difficulty, salt: number): SeededRng {
	const d = difficulty === 'easy' ? 11 : difficulty === 'medium' ? 23 : 41;
	return new SeededRng((((Math.trunc(seed) >>> 0) * 1009 + d * 89 + salt) >>> 0) || 1);
}

