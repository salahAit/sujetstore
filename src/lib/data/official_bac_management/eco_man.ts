function buildEcoManMetadata(
	academicYear: '2023' | '2024' | '2025',
	topicNumber: 1 | 2
): ExamMetadata {
	const sessionAr = `دورة جوان ${academicYear}`;
	return {
		levelId: 'secondaire',
		yearId: '3as',
		yearName: 'السنة الثالثة ثانوي',
		streamId: 'GE',
		streamName: 'تسيير واقتصاد',
		subjectId: 'ECO-MAN',
		subjectName: 'الاقتصاد والمناجمنت',
		trimesterId: 't3',
		trimesterName: sessionAr,
		docType: 'exam',
		academicYear,
		duration: '03 ساعات',
		schoolName: 'منصة SujetStore التعليمية',
		siteUrl: 'https://sujetstore.com',
		font: 'Arabic Transparent',
		customDocTitle: 'امتحان بكالوريا التعليم الثانوي',
		coefficient: 5,
		examSessionAr: sessionAr,
		topicNumber
	};
}

function buildEcoManPaper(opts: {
	slug: string;
	academicYear: '2023' | '2024' | '2025';
	topicNumber: 1 | 2;
	themesAr: string[];
	exercises: [ExerciseBlock, ExerciseBlock, ExerciseBlock];
}): OfficialManagementBacPaperSpec {
	const sessionAr = `دورة جوان ${opts.academicYear}`;
	const topicLabel = opts.topicNumber === 1 ? 'الموضوع الأول' : 'الموضوع الثاني';
	const examDoc: ExamDocument = {
		metadata: buildEcoManMetadata(opts.academicYear, opts.topicNumber),
		exercises: opts.exercises
	};

	return {
		slug: opts.slug,
		grade: '3as_eco',
		yearSubjectId: 756,
		subjectId: 'ECO-MAN',
		subjectNameAr: 'الاقتصاد والمناجمنت',
		streamId: 'GE',
		streamNameAr: 'تسيير واقتصاد',
		academicYear: opts.academicYear,
		topicNumber: opts.topicNumber,
		sessionAr,
		coefficient: 5,
		duration: '03 ساعات',
		pointsSplit: [6, 6, 8] as const,
		templateId: 'secondary/bac_official',
		titleAr: `بكالوريا رسمية في الاقتصاد والمناجمنت — شعبة تسيير واقتصاد (${sessionAr} - ${topicLabel})`,
		themesAr: opts.themesAr,
		examDoc
	};
}

