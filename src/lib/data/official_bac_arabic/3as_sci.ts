function projectCanonicalToStreams(
	canonical: CanonicalSciYearContent
): OfficialArabicBacPaperSpec[] {
	return SCI_STREAMS.map((stream) => {
		const examDoc: ExamDocument = {
			metadata: buildSciMetadata(stream, canonical.academicYear),
			exercises: canonical.exercises
		};
		return {
			slug: `bac-${canonical.academicYear}-${stream.slugTrack}-arabic`,
			grade: stream.grade,
			yearSubjectId: stream.yearSubjectId,
			subjectId: 'ARB-SCI',
			streamId: stream.streamId,
			streamNameAr: stream.streamNameAr,
			academicYear: canonical.academicYear,
			sessionAr: 'دورة جوان ' + canonical.academicYear,
			coefficient: 3,
			duration: '02 ساعة و30 دقيقة',
			hasCriticalEvaluation: false,
			passageKind: canonical.passageKind,
			authorAr: canonical.authorAr,
			templateId: 'secondary/bac_official',
			titleAr: `بكالوريا رسمية في اللغة العربية وآدابها — شعبة ${stream.streamNameAr} (دورة جوان ${canonical.academicYear} - الموضوع الأول)`,
			themesAr: canonical.themesAr,
			sourcePdfRelPath: `pipeline/references_arabic/3as/bac_official/bac_${canonical.academicYear}_sci_arabic_subject.pdf`,
			sourceSolutionPdfRelPath: `pipeline/references_arabic/3as/bac_official/bac_${canonical.academicYear}_sci_arabic_correction.pdf`,
			examDoc
		};
	});
}

