function buildFittedIrabTable(
	entries: Array<{ target: string; irab: string; mark: string }>
): TableBlock {
	const table = buildIrabTableBlock(entries);
	if (table.rows) {
		for (const row of table.rows) {
			const cell = row[1];
			if (cell && typeof cell === 'object' && cell.content.length > 42) {
				cell.content = '........................................';
			}
		}
	}
	return table;
}

function buildNumberedArudBlock(
	numLabel: string,
	opts: Parameters<typeof buildArudScansionBlock>[0]
): ContentBlock {
	const block = buildArudScansionBlock(opts);
	if (block.type === 'text') {
		block.content = `${numLabel} ${block.content}`;
		if (block.answer) {
			block.answer = `${numLabel} ${block.answer}`;
		}
	}
	return block;
}

